export const factions = raw.map((f) => ({
  ...f,
  images: Array.from({ length: IMAGES_PER_FACTION }, (_, i) => {
    const n = i + 1;
    return {
      id: `${f.id}-${n}`,
      src: null,
      fallback: placeholder(f.name, f.color),
      alt: `${f.name} — изображение ${n}`,
    };
  }),
}));

export const factionTabs = factions.map(({ id, tab }) => ({ id, label: tab }));
